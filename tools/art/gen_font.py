ACCENTS = {
    "grave": ["#..", ".#."],
    "acute": ["..#", ".#."],
    "circumflex": [".#.", "#.#"],
    "diaeresis": ["#.#", "..."],
    "tilde": [".##", "#.."],
    "ring": [".#.", "#.#"],
}
COMBINING = {"̀": "grave", "́": "acute", "̂": "circumflex", "̈": "diaeresis",
             "̃": "tilde", "̊": "ring"}


def compose(ch):
    """Build accented letters from base glyph + accent mark."""
    d = unicodedata.normalize("NFD", ch)
    if len(d) != 2:
        return None
    base, mark = d[0], d[1]
    if base not in G:
        return None
    rows = [r for r in G[base]]
    w = len(rows[0])
    full = ["." * w, "." * w] + rows   # 11 rows
    if mark == "̧":                # cedilla
        r9 = list(full[9]); r10 = list(full[10])
        c = w // 2
        r9[c] = "#"; r10[max(0, c - 1)] = "#"
        full[9] = "".join(r9); full[10] = "".join(r10)
        return full
    kind = COMBINING.get(mark)
    if not kind:
        return None
    acc = ACCENTS[kind]
    upper = base.isupper()
    top = 0 if upper else 2
    if base == "i":
        # dotless i + accent
        full = ["." * w, "." * w] + ["..."] * 2 + G["i"][2:]
        top = 2
    off = (w - 3) // 2
    for k in range(2):
        r = list(full[top + k])
        for j, b in enumerate(acc[k]):
            if b == "#" and 0 <= off + j < w:
                r[off + j] = "#"
        full[top + k] = "".join(r)
    return full


def all_glyphs():
    out = {}
    for ch, rows in G.items():
        out[ch] = ["." * len(rows[0])] * 2 + rows
    extra = "àâäáãåçéèêëíìîïñóòôöõúùûüýÿÀÂÄÁÃÅÇÉÈÊËÍÌÎÏÑÓÒÔÖÕÚÙÛÜÝ"
    for ch in extra:
        r = compose(ch)
        if r:
            out[ch] = r
    return out


def build(path):
    glyphs = all_glyphs()
    names = {ch: (f"uni{ord(ch):04X}" if ch != " " else "space") for ch in glyphs}
    order = [".notdef"] + list(names.values())
    fb = FontBuilder(U * ROWS, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap({ord(ch): n for ch, n in names.items()})
    pen_glyphs = {}
    metrics = {}
    # .notdef box
    p = TTGlyphPen(None)
    p.moveTo((0, 0)); p.lineTo((0, 700)); p.lineTo((500, 700)); p.lineTo((500, 0)); p.closePath()
    pen_glyphs[".notdef"] = p.glyph()
    metrics[".notdef"] = (600, 0)
    for ch, rows in glyphs.items():
        pen = TTGlyphPen(None)
        w = len(rows[0])
        for ri, row in enumerate(rows):
            y_top = (BASE - ri) * U
            x = 0
            while x < w:
                if row[x] == "#":
                    x0 = x
                    while x < w and row[x] == "#":
                        x += 1
                    # clockwise contour for TrueType
                    pen.moveTo((x0 * U, y_top)); pen.lineTo((x * U, y_top))
                    pen.lineTo((x * U, y_top - U)); pen.lineTo((x0 * U, y_top - U)); pen.closePath()
                else:
                    x += 1
        pen_glyphs[names[ch]] = pen.glyph()
        adv = (w + 1) * U if ch not in (" ", "\u00a0") else 4 * U
        metrics[names[ch]] = (adv, 0)
    fb.setupGlyf(pen_glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=BASE * U, descent=-(ROWS - BASE) * U)
    fb.setupNameTable({"familyName": "Veridix Pixel", "styleName": "Regular",
                       "copyright": "Original glyphs, French Tech Tycoon. Licensed with the game (MIT OR Apache-2.0)."})
    fb.setupOS2(sTypoAscender=BASE * U, sTypoDescender=-(ROWS - BASE) * U, usWinAscent=BASE * U, usWinDescent=(ROWS - BASE) * U)
    fb.setupPost()
    fb.save(path)
    return len(glyphs)


